#!/usr/bin/env python3
"""Generate the non-authorizing technology rule inventory from WISDOM.md."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
from typing import Sequence
from urllib.parse import urldefrag

import compile_wisdom as compiler


ROOT = Path(__file__).resolve().parents[1]
PREFERENCE_OWNER = "technology_preferences"


def technology_module_ids(parsed: compiler.ParsedWisdom) -> tuple[str, ...]:
    """Find the library through its dependency owner, without a second catalog."""
    selected = {PREFERENCE_OWNER}
    if PREFERENCE_OWNER not in parsed.module_by_id:
        raise compiler.WisdomCompileError("technology preference owner is absent")
    while True:
        expanded = selected | {
            module_id
            for module_id, module in parsed.module_by_id.items()
            if selected.intersection(module["requires"])
        }
        if expanded == selected:
            return tuple(item for item in parsed.module_order if item in selected)
        selected = expanded


def context_rows(parsed: compiler.ParsedWisdom) -> tuple[dict[str, object], ...]:
    """Measure complete source-bound routes, without claiming a token budget."""
    routes = [(f"mode:{mode}", mode, ()) for mode in parsed.view_by_mode]
    routes += [
        (f"profile:{profile['id']}", profile["mode"], tuple(profile["tags"]))
        for profile in parsed.manifest["task_profiles"]
    ]
    rows = []
    for label, mode, tags in routes:
        source_direct = parsed.view_by_mode[mode]["source_direct"]
        modules = tuple(parsed.module_order) if source_direct else compiler.resolve_module_ids(
            parsed, mode=mode, tags=tags)
        module_bytes = sum(
            len(parsed.section_by_id[sid].body)
            for module_id in modules for sid in parsed.module_by_id[module_id]["sections"]
        )
        rows.append({
            "route": label,
            "module_count": len(modules),
            "source_direct": source_direct,
            "selected_bytes": len(parsed.raw) if source_direct else len(parsed.kernel) + module_bytes,
        })
    return tuple(rows)


def render_report(source: Path) -> str:
    parsed = compiler.parse_source(source)
    module_ids = technology_module_ids(parsed)
    sections = [
        parsed.section_by_id[section_id]
        for module_id in module_ids
        for section_id in parsed.module_by_id[module_id]["sections"]
    ]
    rules = sum(len(section.rule_ids) for section in sections)
    references = {
        urldefrag(url)[0]
        for section in sections
        for url in re.findall(rb"\]\((https://[^\s)]+)\)", section.body)
    }
    profiles = [
        profile for profile in parsed.manifest["task_profiles"]
        if set(profile["tags"]).intersection(module_ids)
    ]
    lines = [
        "# Technology module rule report",
        "",
        "Generated by `python3 scripts/report_technology_modules.py` from",
        "[WISDOM.md](../WISDOM.md). This report is a disposable, non-authorizing",
        "view; WISDOM.md remains the sole authored portable authority.",
        "",
        f"Source SHA-256: `{parsed.source_sha256}`. Semantic revision: "
        f"{parsed.manifest['semantic_revision']}.",
        "",
        f"The library adds **{len(module_ids)} conditional modules**, **{rules} "
        f"identified rules**, **{len(profiles)} optional stack profiles**, and "
        f"**{len(references)} distinct reference pages**. Every rule, trigger, "
        "engineering preference, proof prompt, and primary reference appears below.",
        "",
        "The rules are engineering synthesis informed by the cited primary sources.",
        "The sources establish APIs, semantics, and documented failure evidence;",
        "they do not prescribe every architectural preference in this library.",
        "Explicit current user preferences and controlling project conventions take",
        "precedence over technology defaults. Actual runtime semantics and supported",
        "API contracts still apply. No module automatically installs tools or upgrades",
        "a project. The loader selects explicit tags and dependencies; the agent maps",
        "verified project evidence to those tags. It does not auto-detect stacks.",
        "The optional bounded stack inspector supplies advisory candidates; task",
        "route checkpoints support fresh recovery rather than certifying memory.",
        "",
        "Use [the adoption and uncertainty report](TECHNOLOGY_DECISIONS.md) for",
        "conditional choices, rejected universal defaults, research limitations, and",
        "deferred technology coverage. Delivery tests establish route and byte",
        "integrity; they do not establish improved model behavior or performance.",
        "See [the prose, context, and enforcement review](TECHNOLOGY_REVIEW.md) for",
        "the follow-up audit and limits of practical enforcement.",
        "See [the loading and continuity guide](TECHNOLOGY_CONTINUITY.md) for",
        "discovery evidence, route checkpoints, compaction recovery, and host limits.",
        "",
        "## Module index",
        "",
        "| Selection tag / module | Rules | Direct dependencies |",
        "| --- | --- | --- |",
    ]
    for module_id in module_ids:
        module = parsed.module_by_id[module_id]
        ids = [rule for sid in module["sections"] for rule in parsed.section_by_id[sid].rule_ids]
        dependencies = ", ".join(f"`{item}`" for item in module["requires"]) or "None"
        lines.append(f"| `{module_id}` | {', '.join(f'`{rule}`' for rule in ids)} | {dependencies} |")
    lines += ["", "## Optional profiles", "", "These are explicit aliases. Add or omit mechanism tags to match the actual task.", ""]
    for profile in profiles:
        tags = ", ".join(f"`{tag}`" for tag in profile["tags"])
        lines.append(f"- `{profile['id']}`: `{profile['mode']}`; {tags}.")
    lines += [
        "", "## Exact route context footprints", "",
        f"Kernel: **{len(parsed.kernel):,} UTF-8 bytes**. Compiler kernel guard: "
        f"**{parsed.manifest['kernel_max_bytes']:,} bytes**. This guard limits only",
        "the kernel; it is not a model context window or a cap on the selected view.",
        "The following totals include the dependency closure once and exclude any",
        "project companion, system instructions, conversation, tools, and repository",
        "content. Full mode reads the raw source, including the embedded manifest.",
        "Byte counts are not token counts or an optimal prompt-size claim.", "",
        "| Route | Selected modules | Complete WISDOM bytes |",
        "| --- | ---: | ---: |",
    ]
    for row in context_rows(parsed):
        lines.append(f"| `{row['route']}` | {row['module_count']} | {row['selected_bytes']:,} |")
    lines += [
        "", "Use the existing loader's `--selected-context-target-bytes` to report",
        "a project-selected byte target. An over-target result is advisory and never",
        "silently drops an applicable rule. Segments bound individual tool responses,",
        "not the combined model context. Keep the automatic project instruction file",
        "as a short router; read verified applicable content through the loader.",
        "", "## Exact rule inventory", "",
    ]
    for module_id in module_ids:
        module = parsed.module_by_id[module_id]
        lines += [f"Selection tag: `{module_id}`.", ""]
        for section_id in module["sections"]:
            lines.append(parsed.section_by_id[section_id].body.decode("utf-8").replace("\r\n", "\n").rstrip())
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "WISDOM.md")
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "TECHNOLOGY_MODULES.md")
    parser.add_argument("--check", action="store_true", help="reject a stale report without writing")
    args = parser.parse_args(argv)
    try:
        expected = render_report(args.source)
        if args.check:
            actual = args.output.read_bytes()
            if actual != expected.encode("utf-8"):
                raise compiler.WisdomCompileError("technology report is stale; regenerate it")
            print(f"current: {args.output}")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected.encode("utf-8"))
            print(f"wrote: {args.output}")
    except (OSError, compiler.WisdomCompileError) as exc:
        parser.exit(2, f"technology report failed: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
